import { forwardRef } from 'react';
import { ReceiptData, BusinessInfo } from '@/types/receipt';
import { getSettings } from '@/lib/storage';

interface ReceiptPreviewProps {
  data: Partial<ReceiptData>;
  business: BusinessInfo;
  className?: string;
  compact?: boolean;
}

export const ReceiptPreview = forwardRef<HTMLDivElement, ReceiptPreviewProps>(
  ({ data, business, className = '', compact = false }, ref) => {
    const settings = getSettings();
    const customFieldDefs = settings.customFields || [];

    const fields = [
      { label: 'Account Holder', value: data.accountHolder },
      { label: 'Account Number', value: data.accountNumber },
      { label: 'IFSC Code', value: data.ifscCode },
      { label: 'Amount (₹)', value: data.amount ? `₹ ${Number(data.amount).toLocaleString('en-IN')}` : '' },
      { label: 'Date', value: data.date },
      { label: 'Transaction ID', value: data.transactionId },
      { label: 'Reference No', value: data.referenceNumber },
      ...customFieldDefs
        .filter(cf => data.customFields?.[cf.id])
        .map(cf => ({ label: cf.label, value: data.customFields![cf.id] })),
    ].filter(f => f.value);

    return (
      <div
        ref={ref}
        className={`receipt-card relative bg-card border-2 rounded-lg ${compact ? 'p-3' : 'p-5'} max-w-md mx-auto shadow-sm ${className}`}
        style={{ borderColor: `hsl(${business.primaryColor})` }}
      >
        {/* Watermark */}
        {business.showWatermark && (
          <div className="watermark" style={{ color: `hsl(${business.primaryColor})` }}>
            Quick Receipt
          </div>
        )}

        {/* Logo */}
        {business.showLogo && business.logo && (
          <div className={`flex justify-center ${compact ? 'mb-1' : 'mb-2'}`}>
            <img
              src={business.logo}
              alt="Business Logo"
              className={`${compact ? 'h-10 w-10' : 'h-14 w-14'} object-contain rounded-full border`}
            />
          </div>
        )}

        {/* Business Name */}
        {business.showName && (
          <h2
            className={`text-center font-bold mb-0 ${compact ? 'text-base' : 'text-lg'}`}
            style={{ color: `hsl(${business.primaryColor})` }}
          >
            {business.name}
          </h2>
        )}

        {/* Business Address */}
        {business.address && (
          <p className="text-center text-xs text-muted-foreground mt-0.5">{business.address}</p>
        )}

        {/* Business Phone */}
        {business.phone && (
          <p className="text-center text-xs text-muted-foreground mt-0.5">
            Mob:- {business.phone}
          </p>
        )}

        {/* Title */}
        <div className={`text-center ${compact ? 'mb-2 mt-2' : 'mb-4 mt-3'}`}>
          <h3 className="text-xs font-semibold uppercase tracking-[0.2em] text-muted-foreground">
            Transaction Receipt
          </h3>
          <div
            className="w-12 h-0.5 mx-auto mt-1 rounded-full"
            style={{ backgroundColor: `hsl(${business.primaryColor})` }}
          />
        </div>

        {/* Details */}
        <div className={compact ? 'space-y-0.5' : 'space-y-1.5'}>
          {fields.map(field => (
            <div
              key={field.label}
              className={`flex justify-between items-center ${compact ? 'py-0.5' : 'py-1'} border-b border-dashed border-border/50`}
            >
              <span className="receipt-field-label text-xs text-muted-foreground">{field.label}</span>
              <span className={`receipt-field-value ${compact ? 'text-xs' : 'text-sm'} font-medium text-card-foreground`}>{field.value}</span>
            </div>
          ))}
        </div>

        {/* Notes */}
        {data.notes && (
          <div className={`${compact ? 'mt-2' : 'mt-3'} text-xs text-muted-foreground`}>
            <span className="font-medium">Notes: </span>{data.notes}
          </div>
        )}

        {/* Footer */}
        <div className={`${compact ? 'mt-2 pt-2' : 'mt-4 pt-3'} border-t text-center`}>
          {data.serialNumber ? (
            <p className="text-xs text-muted-foreground">Serial No: #{data.serialNumber}</p>
          ) : null}
          <p className="text-[10px] text-muted-foreground/60 mt-1">Generated by Quick Receipt</p>
        </div>

        {/* Disclaimer Note */}
        <div className="receipt-footer-note mt-2 pt-2 border-t border-dashed border-border/50 text-center">
          <p className="text-[9px] leading-tight text-muted-foreground">
            In Case of wrong Account No. or Name Customer Will be responsible. Thank you for transaction with us !!
          </p>
          <p className="text-[9px] leading-tight text-muted-foreground mt-1">
            गलत खाता संख्या या नाम होने की स्थिति में ग्राहक स्वयं जिम्मेदार होगा। हमारे साथ लेन-देन करने के लिए धन्यवाद!!
          </p>
        </div>
      </div>
    );
  }
);

ReceiptPreview.displayName = 'ReceiptPreview';
