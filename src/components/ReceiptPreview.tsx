import { forwardRef } from 'react';
import { ReceiptData, BusinessInfo } from '@/types/receipt';
import { getSettings } from '@/lib/storage';

interface ReceiptPreviewProps {
  data: Partial<ReceiptData>;
  business: BusinessInfo;
  className?: string;
}

export const ReceiptPreview = forwardRef<HTMLDivElement, ReceiptPreviewProps>(
  ({ data, business, className = '' }, ref) => {
    const settings = getSettings();
    const customFieldDefs = settings.customFields || [];

    const fields = [
      { label: 'Account Holder', value: data.accountHolder },
      { label: 'Account Number', value: data.accountNumber },
      { label: 'IFSC Code', value: data.ifscCode },
      { label: 'Amount (₹)', value: data.amount ? `₹ ${Number(data.amount).toLocaleString('en-IN')}` : '' },
      { label: 'Date', value: data.date },
      { label: 'Transaction ID', value: data.transactionId },
      { label: 'Reference No', value: data.referenceNumber },
      ...customFieldDefs
        .filter(cf => data.customFields?.[cf.id])
        .map(cf => ({ label: cf.label, value: data.customFields![cf.id] })),
    ].filter(f => f.value);

    return (
      <div
        ref={ref}
        className={`relative bg-card border-2 rounded-lg p-5 max-w-md mx-auto shadow-sm ${className}`}
        style={{ borderColor: `hsl(${business.primaryColor})` }}
      >
        {/* Watermark */}
        {business.showWatermark && (
          <div className="watermark" style={{ color: `hsl(${business.primaryColor})` }}>
            Quick Receipt
          </div>
        )}

        {/* Logo */}
        {business.showLogo && business.logo && (
          <div className="flex justify-center mb-2">
            <img
              src={business.logo}
              alt="Business Logo"
              className="h-14 w-14 object-contain rounded-full border"
            />
          </div>
        )}

        {/* Business Name */}
        {business.showName && (
          <h2
            className="text-center text-lg font-bold mb-0"
            style={{ color: `hsl(${business.primaryColor})` }}
          >
            {business.name}
          </h2>
        )}

        {/* Business Address */}
        {business.address && (
          <p className="text-center text-xs text-muted-foreground mt-0.5">{business.address}</p>
        )}

        {/* Business Phone */}
        {business.phone && (
          <p className="text-center text-xs text-muted-foreground mt-0.5">
            Mob:- {business.phone}
          </p>
        )}

        {/* Title */}
        <div className="text-center mb-4 mt-3">
          <h3 className="text-xs font-semibold uppercase tracking-[0.2em] text-muted-foreground">
            Transaction Receipt
          </h3>
          <div
            className="w-12 h-0.5 mx-auto mt-1.5 rounded-full"
            style={{ backgroundColor: `hsl(${business.primaryColor})` }}
          />
        </div>

        {/* Details */}
        <div className="space-y-1.5">
          {fields.map(field => (
            <div
              key={field.label}
              className="flex justify-between items-center py-1 border-b border-dashed border-border/50"
            >
              <span className="text-xs text-muted-foreground">{field.label}</span>
              <span className="text-sm font-medium text-card-foreground">{field.value}</span>
            </div>
          ))}
        </div>

        {/* Notes */}
        {data.notes && (
          <div className="mt-3 text-xs text-muted-foreground">
            <span className="font-medium">Notes: </span>{data.notes}
          </div>
        )}

        {/* Footer */}
        <div className="mt-4 pt-3 border-t text-center">
          {data.serialNumber ? (
            <p className="text-xs text-muted-foreground">Serial No: #{data.serialNumber}</p>
          ) : null}
          <p className="text-[10px] text-muted-foreground/60 mt-1">Generated by Quick Receipt</p>
        </div>
      </div>
    );
  }
);

ReceiptPreview.displayName = 'ReceiptPreview';
