import { forwardRef } from 'react';
import { ReceiptData, BusinessInfo } from '@/types/receipt';
import { getSettings } from '@/lib/storage';

interface ReceiptPreviewProps {
  data: Partial<ReceiptData>;
  business: BusinessInfo;
  className?: string;
  compact?: boolean;
}

export const ReceiptPreview = forwardRef<HTMLDivElement, ReceiptPreviewProps>(
  ({ data, business, className = '', compact = false }, ref) => {
    const settings = getSettings();
    const customFieldDefs = settings.customFields || [];

    const fields = [
      { label: 'Account Holder', value: data.accountHolder },
      { label: 'Account Number', value: data.accountNumber },
      { label: 'Bank Name', value: data.bankName },
      { label: 'IFSC Code', value: data.ifscCode },
      { label: 'Amount (₹)', value: data.amount ? `₹ ${Number(data.amount).toLocaleString('en-IN', { minimumFractionDigits: String(data.amount).includes('.') ? 2 : 0, maximumFractionDigits: 2 })}` : '' },
      { label: 'Date', value: data.date },
      { label: 'Transaction ID', value: data.transactionId },
      { label: 'Reference No', value: data.referenceNumber },
      { label: 'Customer Mobile', value: data.customerMobile },
      ...customFieldDefs
        .filter(cf => data.customFields?.[cf.id])
        .map(cf => ({ label: cf.label, value: data.customFields![cf.id] })),
    ].filter(f => f.value);

    return (
      <div
        ref={ref}
        className={`receipt-card relative bg-card border-2 rounded-lg ${compact ? 'p-2' : 'p-3'} max-w-md mx-auto shadow-sm ${className}`}
        style={{ borderColor: `hsl(${business.primaryColor})` }}
      >
        {/* Watermark */}
        {business.showWatermark && (
          <div className="watermark" style={{ color: `hsl(${business.primaryColor})` }}>
            Quick Receipt
          </div>
        )}

        {/* Logo */}
        {business.showLogo && business.logo && (
          <div className={`flex justify-center ${compact ? 'mb-0.5' : 'mb-1'}`}>
            <img
              src={business.logo}
              alt="Business Logo"
              className={`${compact ? 'h-8 w-8' : 'h-10 w-10'} object-contain rounded-full border`}
            />
          </div>
        )}

        {/* Business Name */}
        {business.showName && (
          <h2
            className={`text-center font-bold mb-0 leading-tight ${compact ? 'text-sm' : 'text-base'}`}
            style={{ color: `hsl(${business.primaryColor})` }}
          >
            {business.name}
          </h2>
        )}

        {/* Business Address */}
        {business.address && (
          <p className="text-center text-[10px] text-muted-foreground mt-0">{business.address}</p>
        )}

        {/* Business Phone */}
        {business.phone && (
          <p className="text-center text-[10px] text-muted-foreground mt-0">
            Mob:- {business.phone}
          </p>
        )}

        {/* Title */}
        <div className={`text-center ${compact ? 'mb-1 mt-1' : 'mb-2 mt-1.5'}`}>
          <h3 className="text-[10px] font-semibold uppercase tracking-[0.15em] text-muted-foreground">
            Transaction Receipt
          </h3>
          <div
            className="w-10 h-0.5 mx-auto mt-0.5 rounded-full"
            style={{ backgroundColor: `hsl(${business.primaryColor})` }}
          />
        </div>

        {/* Details */}
        <div className={compact ? 'space-y-0' : 'space-y-0.5'}>
          {fields.map(field => (
            <div
              key={field.label}
              className={`flex justify-between items-center ${compact ? 'py-0' : 'py-0.5'} border-b border-dashed border-border/50`}
            >
              <span className="receipt-field-label text-[10px] text-muted-foreground">{field.label}</span>
              <span className={`receipt-field-value text-[11px] font-medium text-card-foreground`}>{field.value}</span>
            </div>
          ))}
        </div>

        {/* Notes */}
        {data.notes && (
          <div className={`${compact ? 'mt-1' : 'mt-1.5'} text-[10px] text-muted-foreground`}>
            <span className="font-medium">Notes: </span>{data.notes}
          </div>
        )}

        {/* Footer */}
        <div className={`${compact ? 'mt-1 pt-1' : 'mt-2 pt-1.5'} border-t text-center`}>
          {data.serialNumber ? (
            <p className="text-[10px] text-muted-foreground">Serial No: #{data.serialNumber}</p>
          ) : null}
          <p className="text-[8px] text-muted-foreground/60 mt-0.5">Generated by Quick Receipt</p>
        </div>

        {/* Disclaimer Note (Hindi only) */}
        <div className="receipt-footer-note mt-1 pt-1 border-t border-dashed border-border/50 text-center">
          <p className="text-[8px] leading-tight text-muted-foreground">
            गलत खाता संख्या या नाम होने की स्थिति में ग्राहक स्वयं जिम्मेदार होगा। हमारे साथ लेन-देन करने के लिए धन्यवाद!!
          </p>
          <p className="text-[8px] leading-tight text-muted-foreground mt-0.5">
            अगर आपके खाते में पैसे जमा नहीं हुए तो इसकी जानकारी 7 दिनों के अंदर दें। 7 दिनों बाद हमारी कोई जिम्मेदारी नहीं होगी।
          </p>
        </div>
      </div>
    );
  }
);

ReceiptPreview.displayName = 'ReceiptPreview';
